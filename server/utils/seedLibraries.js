const seedLibrariesIfEmpty = async () => {
  try {
    const exerciseCount = await Exercise.countDocuments();
    if (exerciseCount === 0) {
      await Exercise.insertMany(initialExercises);
      console.log(`✅ Seeded ${initialExercises.length} default exercises into Exercise library.`);
    }

    const foodCount = await FoodItem.countDocuments();
    if (foodCount === 0) {
      await FoodItem.insertMany(initialFoods);
      console.log(`✅ Seeded ${initialFoods.length} default food items into FoodItem library.`);
    }
  } catch (error) {
    console.error('⚠️ Notice: Seed library check failed:', error.message);
  }
};

module.exports = { seedLibrariesIfEmpty };
